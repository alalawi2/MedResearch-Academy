const mass = { mcg: 1, mg: 1000, g: 1000000 };
const cleanName = (value) =>
  String(value).toLowerCase().replace(/[™®]/g, "").replace(/\s+/g, " ").trim();
export function identifyNutrient(value) {
  const full = cleanName(value);
  if (/calcifediol|calcidiol/i.test(full)) return null;
  if (
    /\b(blend|complex|combination|with)\b/.test(full) &&
    !/^probiotics? blend(?:\s*\([^)]*\))?$/.test(full)
  )
    return null;
  const root = full.replace(/\s*\([^)]*\)\s*$/, "").trim();
  for (const [name, info] of Object.entries(nutrientCatalog)) {
    if ([name, ...info.aliases].some((alias) => cleanName(alias) === full))
      return name;
  }
  for (const [name, info] of Object.entries(nutrientCatalog)) {
    if ([name, ...info.aliases].some((alias) => cleanName(alias) === root))
      return name;
  }
  return null;
}
export function canonicalUnit(value) {
  const key = String(value)
    .trim()
    .toLowerCase()
    .replace(/[μµ]/g, "u")
    .replace(/\s+/g, " ");
  const known = {
    ug: "mcg",
    mcg: "mcg",
    microgram: "mcg",
    micrograms: "mcg",
    mg: "mg",
    milligram: "mg",
    milligrams: "mg",
    g: "g",
    gram: "g",
    grams: "g",
    iu: "IU",
    cfu: "CFU",
    ml: "mL",
    "mcg dfe": "mcg DFE",
    mcgdfe: "mcg DFE",
    "mcg rae": "mcg RAE",
    mcgrae: "mcg RAE",
    "mg ne": "mg NE",
    "billion cfu": "billion CFU",
    "million cfu": "million CFU",
  };
  return known[key] || String(value).trim();
}
export function normalizeQuantity(nutrient, amount, unit) {
  if (
    !Object.hasOwn(nutrientCatalog, nutrient) ||
    !Number.isFinite(amount) ||
    amount < 0
  )
    return null;
  const info = nutrientCatalog[nutrient];
  const from = canonicalUnit(unit);
  if (!info.units.includes(from)) return null;
  if (nutrient === "Vitamin D" && from === "IU")
    return { amount: amount / 40, unit: "mcg" };
  if (from === "billion CFU" || from === "million CFU")
    return {
      amount: amount * (from === "billion CFU" ? 1e9 : 1e6),
      unit: "CFU",
    };
  if (Object.hasOwn(mass, from) && Object.hasOwn(mass, info.baseUnit))
    return {
      amount: (amount * mass[from]) / mass[info.baseUnit],
      unit: info.baseUnit,
    };
  return { amount, unit: from };
}
